#!/usr/bin/env python3
"""Write executed.tsv: every test file whose tests ran on this commit, and how.

Reads the same logs as regression_matrix.py:
  rust-all.log (cargo test --release --all-features --no-fail-fast),
  go.log (go test -v), py-ai.log / py-ms.log (pytest -rA),
  ts-<pkg>.tap (tsx --test --test-reporter=tap).
A Rust test target is recorded with its pass/fail/ignored counts; a source
file is recorded when it holds unit tests and the library's unit-test binary
ran. Usage: executed_from_logs.py <repo-root> <logs-dir> <out-tsv>
"""
import os
import re
import sys
from collections import Counter, defaultdict


def main():
    root, logs, out = sys.argv[1], sys.argv[2], sys.argv[3]
    rows = {}
    per_target = defaultdict(Counter)
    target = None
    rust_log = os.path.join(logs, "rust-all.log")
    if os.path.exists(rust_log):
        for line in open(rust_log, encoding="utf-8", errors="replace"):
            m = re.match(r"\s*Running (unittests src/lib\.rs|unittests src/bin/(\S+)\.rs|tests/([a-z0-9_]+)\.rs)", line)
            if m:
                target = "lib" if "src/lib.rs" in m.group(1) else (f"bin:{m.group(2)}" if m.group(2) else m.group(3))
                continue
            m = re.match(r"^test \S+ \.\.\. (ok|FAILED|ignored)", line)
            if m and target:
                per_target[target][m.group(1)] += 1
    for t, c in per_target.items():
        desc = f"cargo test --release --all-features: {c['ok']} ok, {c['FAILED']} failed, {c['ignored']} ignored"
        if t == "lib":
            for dirpath, _, files in os.walk(os.path.join(root, "graphite-core/src")):
                for f in files:
                    p = os.path.join(dirpath, f)
                    if f.endswith(".rs") and "#[test]" in open(p, encoding="utf-8").read() or (
                            f.endswith(".rs") and "#[tokio::test]" in open(p, encoding="utf-8").read()):
                        rows[os.path.relpath(p, root)] = f"lib unit tests ({desc})"
        elif t.startswith("bin:"):
            rows[f"graphite-core/src/bin/{t[4:]}.rs"] = desc
        else:
            rows[f"graphite-core/tests/{t}.rs"] = desc
    go_log = os.path.join(logs, "go.log")
    if os.path.exists(go_log):
        text = open(go_log, encoding="utf-8", errors="replace").read()
        passed = len(re.findall(r"^--- PASS", text, re.M))
        failed = len(re.findall(r"^--- FAIL", text, re.M))
        ok = "go exit 0" in text
        for f in sorted(os.listdir(os.path.join(root, "sdk/go"))):
            if f.endswith("_test.go"):
                rows[f"sdk/go/{f}"] = f"go test -v: {passed} pass, {failed} fail, exit {'0' if ok else 'non-zero'}" + (
                    " (liveserver tag not built: needs a live Core)" if f == "live_server_test.go" else "")
    for log, rel in (("py-ai.log", "python-ai-layer/test_intent_parser.py"),
                     ("py-ms.log", "tools/mainnet-sample/test_mainnet_sample.py")):
        p = os.path.join(logs, log)
        if os.path.exists(p):
            last = [l for l in open(p, encoding="utf-8", errors="replace") if re.search(r"\d+ passed", l)]
            rows[rel] = f"pytest: {last[-1].strip(' =\n') if last else 'no summary'}"
    for pkgdir, tap in (("integrations/agent-guard", "agent-guard"), ("integrations/mcp-server", "mcp-server"),
                        ("integrations/solana-agent-kit", "solana-agent-kit"), ("integrations/vercel-ai", "vercel-ai"),
                        ("sdk/typescript/src", "typescript"), ("dashboard/src", "dashboard")):
        p = os.path.join(logs, f"ts-{tap}.tap")
        if not os.path.exists(p):
            continue
        s = dict(re.findall(r"^# (tests|pass|fail|skipped|cancelled) (\d+)", open(p).read(), re.M))
        for f in sorted(os.listdir(os.path.join(root, pkgdir))):
            if f.endswith(".test.ts"):
                rows[f"{pkgdir}/{f}"] = (f"tsx --test (package suite): {s.get('pass')}/{s.get('tests')} pass, "
                                         f"{s.get('fail')} fail, {s.get('skipped')} skipped")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("# path\thow it was executed on this commit (generated by executed_from_logs.py)\n")
        for k in sorted(rows):
            fh.write(f"{k}\t{rows[k]}\n")
    print(f"{len(rows)} files recorded as executed")


if __name__ == "__main__":
    main()
